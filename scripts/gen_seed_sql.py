"""Generate supabase/seed.sql from the legacy demo data plus KSPCB reference data.

Run from the repo root:  python scripts/gen_seed_sql.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED = json.loads((ROOT / "backend/scm/data/legacy_seed.json").read_text())
SITES = json.loads((ROOT / "backend/scm/data/kspcb_disposal_sites.json").read_text())

import sys

sys.path.insert(0, str(ROOT / "backend"))
from scm import constants as c  # noqa: E402


def q(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def point(lat, lon) -> str:
    if lat is None:
        return "null"
    return f"extensions.st_setsrid(extensions.st_makepoint({lon}, {lat}), 4326)::extensions.geography"


out = ["-- Generated by scripts/gen_seed_sql.py. Do not edit by hand.", "begin;", ""]

out.append("insert into public.clusters (name, location) values")
out.append(",\n".join(f"  ({q(n)}, {point(lat, lon)})" for n, (lat, lon) in SEED["clusters"].items()))
out.append("on conflict (name) do nothing;\n")

out.append(
    "insert into public.materials (code, category, hazardous, hsn_code, gst_rate_pct, standard_note,"
    " co2_virgin_kg_per_t, pm10_avoided_kg_per_t, so2_avoided_kg_per_t) values"
)
rows = []
for code, t in SEED["taxonomy"].items():
    rows.append(
        f"  ({q(code)}, {q(t['category'])}, {q(t['hazard'])}, {q(t['hsnCode'])}, {q(t['defaultGstRate'])}, "
        f"{q(t['standardNote'])}, {q(c.CO2_VIRGIN_MATERIAL_KG_PER_TON.get(code))}, "
        f"{q(c.PM10_AVOIDED_KG_PER_TON.get(code))}, {q(c.SO2_AVOIDED_KG_PER_TON.get(code))})"
    )
out.append(",\n".join(rows))
out.append("on conflict (code) do nothing;\n")

out.append(
    "insert into public.carriers (id, name, cluster, location, vehicle_type, capacity_t, rate_floor_inr_per_t_km,"
    " hazmat_license) values"
)
out.append(
    ",\n".join(
        f"  ({q(x['id'])}, {q(x['name'])}, {q(x['cluster'])}, {point(x['lat'], x['lon'])}, {q(x['vehicle_type'])}, "
        f"{q(x['capacity_tons'])}, {q(x['rate_floor_inr_per_ton_km'])}, {q(x['hazmat_transport_license'])})"
        for x in SEED["carriers"].values()
    )
)
out.append("on conflict (id) do nothing;\n")

out.append("insert into public.seed_facility_docs (doc) values")
out.append(",\n".join(f"  ({q(json.dumps(f, sort_keys=True))}::jsonb)" for f in SEED["facilities"].values()))
out.append("on conflict ((doc ->> 'id')) do nothing;\n")
out.append("select public.upsert_facility_doc(doc) from public.seed_facility_docs;\n")

# Fields the relational columns do not hold are kept in facilities.extra.
known = {
    "id", "name", "role", "cluster", "lat", "lon", "material", "material_category", "hazardous",
    "certified_hazard_handler", "volume_tons_per_month", "cost_floor_inr_per_ton", "cost_ceiling_inr_per_ton",
    "gstin", "kspcb_consent_id", "quality_requirements", "lab_assay", "sensor_adjustment", "xgn_details",
}
out.append(
    "update public.facilities f set extra = s.doc - array["
    + ", ".join(q(k) for k in sorted(known))
    + "]\nfrom public.seed_facility_docs s where f.id = s.doc ->> 'id';"
)
out.append("")

out.append(
    "insert into public.disposal_sites (id, name, kind, district, location, design_capacity_t, annual_capacity_tpa,"
    " status, notes, source) values"
)
out.append(
    ",\n".join(
        f"  ({q(s['id'])}, {q(s['name'])}, {q(s['kind'])}, {q(s['district'])}, {point(s.get('lat'), s.get('lon'))}, "
        f"{q(s.get('design_capacity_t'))}, {q(s.get('annual_capacity_tpa'))}, {q(s['status'])}, {q(s.get('notes'))}, "
        f"{q(s['source'])})"
        for s in SITES
    )
)
out.append("on conflict (id) do nothing;\n")
out.append("commit;")

(ROOT / "supabase/seed.sql").write_text("\n".join(out) + "\n")
print(f"wrote supabase/seed.sql ({len(SEED['facilities'])} facilities, {len(SITES)} disposal sites)")
